<h5>Content library search</h5>
<p>Use the header search box or <strong>Content → Library search</strong> to find pages, posts, and media in one place. Search matches titles, slugs, SEO fields, LLM summaries, post tags, and media filenames/alt text (minimum 2 characters).</p>
<p>Results respect your capabilities: you only see modules you can view.</p>
<p>Admin: <code>/admin/search?q=…</code></p>
