<h5>Comments</h5>
<p>Moderate visitor comments on published blog posts. Enable or disable comments under <strong>System → General → Discussion</strong>.</p>
<ul>
<li><strong>Pending</strong> — Awaiting approval when moderation is enabled.</li>
<li><strong>Approve</strong> — Makes the comment visible on the public post.</li>
<li><strong>Spam / Trash</strong> — Hide abusive or unwanted comments.</li>
</ul>
<p>Public comment forms appear at the bottom of each post when comments are enabled. Rate limiting (per IP / hour) is configured under General → Discussion.</p>
