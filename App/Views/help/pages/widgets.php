<h5>Widgets</h5>
<p>Manage sidebar and footer widget areas on the public site (WordPress-style).</p>
<ul>
<li><strong>Sidebar</strong> — Shown on public pages when enabled in <strong>General → Discussion → Show sidebar</strong>.</li>
<li><strong>Footer</strong> — Rendered above the site footer when widgets are configured.</li>
<li>Widget types: Recent posts, Categories, Tag cloud, Search box, Custom HTML.</li>
</ul>
<p>Drag widgets by the ⋮⋮ handle to reorder (top to bottom). Order is saved when you click <strong>Save widgets</strong>.</p>
